// Generates `data/lessonMeta.ts` — the metadata-only lesson index that client
// components import. Keeping it as a generated literal (instead of deriving it
// from `data/lessons.ts`) means the paid lesson bodies never end up in the
// browser bundle.
//
// Run `npm run gen:lesson-meta` after editing lessons. CI fails if the file is
// stale (see tests/curriculum.test.ts).

import fs from 'node:fs';
import { LESSONS } from '@/data/lessons';
import type { LessonMeta } from '@/data/types';

const meta: LessonMeta[] = LESSONS.map(({ c: _content, ...rest }) => rest);

const out =
  '// AUTO-GENERATED by scripts/gen-lesson-meta.ts — do not edit by hand.\n' +
  '// Metadata only: lesson bodies are served by /api/lessons/[id].\n' +
  "import type { LessonMeta } from './types';\n\n" +
  'export const LESSON_META: LessonMeta[] = ' +
  JSON.stringify(meta, null, 2) +
  ';\n';

fs.writeFileSync('data/lessonMeta.ts', out);
console.log(`wrote data/lessonMeta.ts (${meta.length} lessons, no content)`);
